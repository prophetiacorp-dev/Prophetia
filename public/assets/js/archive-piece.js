  const root = document.querySelector("[data-piece-root]");
  if (!root) return;

  const params = new URLSearchParams(window.location.search);
  const rawId = (params.get("id") || "somewhere").trim().toLowerCase();
  const rawVersion = (params.get("version") || "").trim().toLowerCase();
  const normalizedId = rawId.replace(/[-_\s]/g, "");

  const pieceBase = PIECES[normalizedId];

  if (!pieceBase) {
    renderNotFound(root, rawId);
    return;
  }

  const selectedVersion =
    (rawVersion && pieceBase.versions?.[rawVersion]) ||
    pieceBase.versions?.default ||
    pieceBase.versions?.["full-color"] ||
    Object.values(pieceBase.versions || {})[0];

  if (!selectedVersion) {
    renderNotFound(root, rawId);
    return;
  }

  const piece = {
    ...pieceBase,
    ...selectedVersion
  };

  renderPiece(piece, rawVersion);

  function renderPiece(data, versionSlug) {
    setText("[data-piece-collection]", data.collection);
    setText("[data-piece-title]", data.title);
    setText("[data-piece-subtitle]", data.subtitle);
    setText("[data-piece-lede]", data.lede);
    setText("[data-piece-story]", data.story);
    setText("[data-piece-inspiration]", data.inspiration);
    setText("[data-piece-tone]", data.tone);
    setText("[data-piece-color]", data.color);
    setText("[data-piece-intention]", data.intention);
    setText("[data-piece-language]", data.language);

    const mainImage = document.querySelector("[data-piece-main-image]");
    if (mainImage && data.images?.main) {
      mainImage.src = data.images.main.src;
      mainImage.alt = data.images.main.alt;
    }

    const cta = document.querySelector("[data-piece-cta]");
    if (cta) {
      const versionQuery = data.productVersion
        ? `&version=${encodeURIComponent(data.productVersion)}`
        : "";

      const targetHref = `../../producto?id=${encodeURIComponent(data.productId)}${versionQuery}`;

      cta.href = targetHref;
      cta.setAttribute("aria-label", `Adquirir ${data.title}`);

      cta.addEventListener("click", function (event) {
        event.preventDefault();

        const html = document.documentElement;
        if (html.classList.contains("is-transitioning")) return;

        html.classList.add("is-transitioning");

        window.setTimeout(function () {
          window.location.href = targetHref;
        }, 320);
      });
    }

    document.title = versionSlug
      ? `${data.brand} — ${data.title} — ${formatVersionLabel(versionSlug)}`
      : `${data.brand} — ${data.title}`;

    renderGallery(data.images?.gallery || []);
  }

  function renderGallery(items) {
    const galleryRoot = document.querySelector("[data-piece-gallery]");
    const template = document.getElementById("galleryItemTemplate");

    if (!galleryRoot || !template || !Array.isArray(items)) return;

    galleryRoot.innerHTML = "";

    items.forEach((item) => {
      const fragment = template.content.cloneNode(true);
      const img = fragment.querySelector(".piece-gallery-card__img");
      const type = fragment.querySelector(".piece-gallery-card__type");

      img.src = item.src;
      img.alt = item.alt || item.type || "Imagen de galería";
      type.textContent = item.type || "Archive View";

      galleryRoot.appendChild(fragment);
    });
  }

  function setText(selector, value) {
    const node = document.querySelector(selector);
    if (node && typeof value === "string") {
      node.textContent = value;
    }
  }

  function formatVersionLabel(value) {
    return String(value)
      .split("-")
      .map(part => part.charAt(0).toUpperCase() + part.slice(1))
      .join(" ");
  }

  function renderNotFound(container, failedId) {
    container.innerHTML = `
      <section class="piece-empty" aria-labelledby="piece-empty-title">
        <p class="piece-empty__eyebrow">PROPHETIA</p>
        <h1 class="piece-empty__title" id="piece-empty-title">Piece not found</h1>
        <p class="piece-empty__text">
          No existe ninguna pieza asociada a <strong>${escapeHtml(failedId)}</strong>.
          Revisa el parámetro <code>?id=</code> o vuelve al archivo editorial.
        </p>
        <a class="piece-empty__link" href="./archive-summer">
          Volver a Summer Archive
        </a>
      </section>
    `;
    document.title = "PROPHETIA — Piece not found";
  }

  function escapeHtml(value) {
    return String(value).replace(/[&<>"']/g, function (char) {
      const map = {
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        "\"": "&quot;",
        "'": "&#039;"
      };
      return map[char];
    });
  }
